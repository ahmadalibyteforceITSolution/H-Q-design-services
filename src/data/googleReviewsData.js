/**
 * Client-side fetcher for Google Reviews with caching & fallback
 */
export async function fetchGoogleReviews() {
  const CACHE_KEY = 'hq_google_reviews_cache_v1';
  const CACHE_TIME_KEY = 'hq_google_reviews_timestamp';
  const ONE_HOUR = 3600 * 1000;

  // Check browser cache first
  try {
    const cached = sessionStorage.getItem(CACHE_KEY);
    const cachedTime = sessionStorage.getItem(CACHE_TIME_KEY);
    if (cached && cachedTime && (Date.now() - parseInt(cachedTime, 10) < ONE_HOUR)) {
      return JSON.parse(cached);
    }
  } catch (e) {
    // ignore sessionStorage errors
  }

  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 4000);

    const res = await fetch('/api/reviews', {
      signal: controller.signal,
      headers: { 'Accept': 'application/json' }
    });
    clearTimeout(timeoutId);

    if (res.ok) {
      const data = await res.json();
      if (data && data.reviews && data.reviews.length > 0) {
        try {
          sessionStorage.setItem(CACHE_KEY, JSON.stringify(data));
          sessionStorage.setItem(CACHE_TIME_KEY, Date.now().toString());
        } catch (e) {}
        return data;
      }
    }
  } catch (err) {
    // Network or abort error: fallback gracefully
  }

  // Return local verified dataset
  return {
    source: 'local_verified_dataset',
    place_id: GOOGLE_BUSINESS.placeId,
    cid: GOOGLE_BUSINESS.cid,
    business_name: GOOGLE_BUSINESS.name,
    formatted_address: GOOGLE_BUSINESS.address,
    rating: GOOGLE_BUSINESS.rating,
    user_ratings_total: initialGoogleReviews.length,
    write_review_url: GOOGLE_BUSINESS.writeReviewUrl,
    google_maps_url: GOOGLE_BUSINESS.mapsUrl,
    reviews: initialGoogleReviews
  };
}

